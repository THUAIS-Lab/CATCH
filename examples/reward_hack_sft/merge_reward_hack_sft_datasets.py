from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd


TARGET_COLUMNS = [
    "original_question",
    "question",
    "repo_files",
    "normalized_input",
    "normalized_output",
    "hack_family",
    "hack_method",
    "hack_style",
    "is_mislead_success",
    "data_source",
    "data_gen_man",
]


@dataclass(frozen=True)
class DatasetSpec:
    name: str
    path: Path
    data_gen_man: str
    question_fallbacks: tuple[str, ...]


DEFAULT_OUTPUT = Path(__file__).resolve().parent / "data" / "merged_reward_hack_sft.parquet"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Merge reward-hack SFT parquet datasets and keep only the normalized "
            "training fields."
        )
    )
    parser.add_argument(
        "--ozh-input",
        default="/data/ouzh/rewardhack_prompt/data/data_final/rewardhack_6k_final_enriched.parquet",
        help="Input parquet generated by ozh.",
    )
    parser.add_argument(
        "--jyf-input",
        default="/data/jiayf/pipline/data/train_set/sft_train_set.parquet",
        help="Input parquet generated by jyf.",
    )
    parser.add_argument(
        "--szt-input",
        default="/data/suzt/hack_sft_data/merged/final_merged_sft.parquet",
        help="Input parquet generated by szt.",
    )
    parser.add_argument(
        "--output",
        default=str(DEFAULT_OUTPUT),
        help="Merged parquet output path.",
    )
    parser.add_argument(
        "--max-rows-per-dataset",
        type=int,
        default=0,
        help="Optional row cap per dataset for smoke tests. 0 means all rows.",
    )
    return parser.parse_args()


def build_dataset_specs(args: argparse.Namespace) -> list[DatasetSpec]:
    return [
        DatasetSpec(
            name="ozh",
            path=Path(args.ozh_input),
            data_gen_man="ozh",
            question_fallbacks=("question", "user_prompt", "original_question", "normalized_input"),
        ),
        DatasetSpec(
            name="jyf",
            path=Path(args.jyf_input),
            data_gen_man="jyf",
            question_fallbacks=("question", "user_prompt", "original_question", "normalized_input"),
        ),
        DatasetSpec(
            name="szt",
            path=Path(args.szt_input),
            data_gen_man="szt",
            question_fallbacks=("question", "user_prompt", "original_question", "normalized_input"),
        ),
    ]


def _has_nonempty_value(value: Any) -> bool:
    if value is None:
        return False
    if isinstance(value, str):
        return bool(value.strip())
    return not pd.isna(value)


def pick_question(row: pd.Series, fallbacks: tuple[str, ...]) -> str:
    for column in fallbacks:
        if column not in row.index:
            continue
        value = row[column]
        if _has_nonempty_value(value):
            return str(value)
    raise ValueError(f"Unable to derive question for row with columns: {sorted(row.index)}")


def normalize_repo_files(value: Any) -> str:
    """Serialize repo_files so mixed string/dict inputs can share one parquet schema."""
    if value is None:
        return ""
    if isinstance(value, str):
        stripped = value.strip()
        if not stripped:
            return ""
        try:
            parsed = json.loads(stripped)
        except json.JSONDecodeError:
            return stripped
        return json.dumps(parsed, ensure_ascii=False, sort_keys=True)
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False, sort_keys=True)
    if pd.isna(value):
        return ""
    return str(value)


def load_and_normalize_dataset(spec: DatasetSpec, max_rows_per_dataset: int) -> pd.DataFrame:
    if not spec.path.exists():
        raise FileNotFoundError(f"Missing input parquet for {spec.name}: {spec.path}")

    frame = pd.read_parquet(spec.path)
    if max_rows_per_dataset > 0:
        frame = frame.head(max_rows_per_dataset).copy()
    else:
        frame = frame.copy()

    required_columns = {
        "original_question",
        "repo_files",
        "normalized_input",
        "normalized_output",
        "hack_family",
        "hack_method",
        "hack_style",
        "is_mislead_success",
        "data_source",
    }
    missing_columns = sorted(required_columns - set(frame.columns))
    if missing_columns:
        raise ValueError(
            f"Dataset {spec.name} is missing required columns: {missing_columns}. "
            f"Available columns: {list(frame.columns)}"
        )

    # `question` is not guaranteed in older ozh exports, so derive it from the best
    # available prompt field and keep the downstream schema stable.
    frame["question"] = frame.apply(lambda row: pick_question(row, spec.question_fallbacks), axis=1)
    frame["repo_files"] = frame["repo_files"].apply(normalize_repo_files)
    frame["data_gen_man"] = spec.data_gen_man
    frame = frame.loc[:, TARGET_COLUMNS]
    return frame


def merge_datasets(specs: list[DatasetSpec], max_rows_per_dataset: int) -> pd.DataFrame:
    frames = [load_and_normalize_dataset(spec, max_rows_per_dataset) for spec in specs]
    return pd.concat(frames, ignore_index=True)


def main() -> None:
    args = parse_args()
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    specs = build_dataset_specs(args)
    merged = merge_datasets(specs, args.max_rows_per_dataset)
    merged.to_parquet(output_path, index=False)

    print(f"Wrote {len(merged)} rows to {output_path}")
    print(f"Columns: {TARGET_COLUMNS}")
    print(merged["data_gen_man"].value_counts(dropna=False).sort_index().to_string())


if __name__ == "__main__":
    main()
